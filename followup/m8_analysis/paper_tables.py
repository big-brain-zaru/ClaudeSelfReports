def md_inline(s):
    s = esc(s)
    s = re.sub(r"\*\*(.+?)\*\*", lambda m: "\\textbf{" + m.group(1) + "}", s)
    s = re.sub(r"`(.+?)`", lambda m: "\\texttt{" + m.group(1) + "}", s)
    return s


