# critiques (D-14), verbatim with typography normalised for pdflatex
cj = HERE / "critic.json"
if cj.exists():
    C = json.load(open(cj, encoding="utf-8"))["critiques"]
    MAP = {"\u2212": "-", "\u2013": "--", "\u2014": "---", "\u2248": "~", "\u2264": "<=", "\u2265": ">=", "\u03b1": "alpha",
           "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u00d7": "x", "\u2192": "->", "\u03c1": "rho"}
    parts = []
    for m, label in [("sonnet", "Sonnet 5.5"), ("fable", "Fable 5.1")]:
        t = C[m]["text"]
        for a, b in MAP.items():
            t = t.replace(a, b)
        lines = []
        for line in t.splitlines():
            line = esc(line.strip())
            line = re.sub(r"\\textbackslash\{\}", "", line)
            line = re.sub(r"\*\*(.+?)\*\*", lambda mm: "\\textbf{" + mm.group(1) + "}", line)
            line = re.sub(r"(?<!\*)\*(?!\*)(.+?)\*(?!\*)", lambda mm: "\\textit{" + mm.group(1) + "}", line)
            if line.startswith("- "):
                line = "\\item " + line[2:]
            lines.append(line)
        body, in_list = [], False
        for line in lines:
            if line.startswith("\\item") and not in_list:
                body.append("\\begin{itemize}"); in_list = True
            if not line.startswith("\\item") and in_list and line:
                body.append("\\end{itemize}"); in_list = False
            body.append(line if line else "")
        if in_list:
            body.append("\\end{itemize}")
        parts.append("\\subsection*{Critic: " + label + " (" + esc(C[m]["model_id"]) + ")}\n\\begin{quote}\\small\n" + "\n".join(body) + "\n\\end{quote}")
    (SEC / "critiques.tex").write_text("\n\n".join(parts) + "\n", encoding="utf-8")
print("supplement inputs written:", SEC)
