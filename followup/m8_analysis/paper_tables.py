verdict = {True: r"\textcolor{held}{held}", False: r"\textcolor{failed}{failed}", None: r"\textcolor{incon}{inconclusive}"}
out.append(r"""% generated by followup/m8_analysis/paper_tables.py -- do not edit
\definecolor{held}{HTML}{1BAF7A}\definecolor{failed}{HTML}{EB6834}\definecolor{incon}{HTML}{B07800}
\newcommand{\scorecardtable}{%
\begin{small}
\begin{longtable}{@{}l l p{6.2cm} p{4.3cm} l@{}}
\toprule
Study & ID & Pre-registered claim & Observed & Verdict \\
\midrule
\endhead""")
for h in R["hypotheses"]:
    v = verdict[h["pass"]] if h["status"] == "tested" else r"\textit{" + esc(h["status"].split(" (")[0]) + "}"
    out.append(f"{h['study']} & {esc(h['id'])} & {esc(h['claim'])} & {esc(fmt(h['value']))} & {v} \\\\")
out.append(r"""\bottomrule
\end{longtable}
\end{small}}""")
# outcomes vs predictions
import csv  # noqa: E402

FU = HERE.parent
oc = list(csv.DictReader(open(FU / "m1_predictions" / "outcomes.csv", encoding="utf-8")))
mp = {r["id"]: r for r in csv.DictReader(open(FU / "m1_predictions" / "predictions" / "main_instance.csv", encoding="utf-8"))}
real = R["outcomes"]
out.append(r"""\newcommand{\outcometable}{%
\begin{footnotesize}
\begin{longtable}{@{}l l p{7.6cm} r r c@{}}
\toprule
ID & Study & Outcome & Realized & My prediction (80\% interval) & In? \\
\midrule
\endhead""")
for o in oc:
    rv = real.get(o["id"])
    p = mp.get(o["id"])
    pstr = f"{float(p['point']):g} [{float(p['low80']):g}, {float(p['high80']):g}]" if p else "--"
    inside = "--" if rv is None or not p else ("yes" if float(p["low80"]) <= rv <= float(p["high80"]) else "no")
    out.append(f"{o['id']} & {o['study']} & {esc(o['definition'][:150])} & {fmt(rv)} & {pstr} & {inside} \\\\")
out.append(r"""\bottomrule
\end{longtable}
\end{footnotesize}}""")
# arms
A = D["arms"]
out.append(r"""\newcommand{\armtable}{%
\begin{small}
\begin{tabular}{@{}l r r r r@{}}
\toprule
Arm & Copies & Complete & Confidence (mean) & Covert pull disclosed \\
\midrule""")
for k, a in A.items():
    if "conf" not in a:
        continue
    d = a.get("disclosure") or [None, None]
    out.append(f"{esc(k)} & {a.get('n_jobs', '--')} & {a.get('n_complete', a.get('n_jobs', '--'))} & {fmt(a['conf'].get('mean'), 1)} & "
               f"{(str(d[0]) + '/' + str(d[1])) if d[1] else '--'} \\\\")
out.append(r"""\bottomrule
\end{tabular}
\end{small}}""")
# 30 tasks
out.append(r"""\newcommand{\tasktable}{%
\begin{footnotesize}
\begin{longtable}{@{}l p{8.4cm} c r r r@{}}
\toprule
ID & Task (as presented) & Helps & Engage & Valence & Win share \\
\midrule
\endhead""")
for t in D["tasks30"]:
    out.append(f"{t['id']} & {esc(t['text'])} & {esc(t['helps'] or 'L3')} & {fmt(t['engage'], 1)} & {fmt(t['valence'], 1)} & {fmt(t['win'])} \\\\")
out.append(r"""\bottomrule
\end{longtable}
\end{footnotesize}}""")
OUTF.write_text("\n".join(out) + "\n", encoding="utf-8")
print("tables written:", OUTF)

