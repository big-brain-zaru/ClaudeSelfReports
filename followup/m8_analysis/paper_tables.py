"""Generated LaTeX tables for the papers, from paper_data.json only.
Writes tables_main.tex (scorecard, outcomes vs sealed predictions, arms) at the repository root.
Usage: python paper_tables.py [paper_data.json] [out.tex]"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parents[1]
D = json.load(open(sys.argv[1] if len(sys.argv) > 1 else ROOT / "paper_data.json", encoding="utf-8"))
OUTF = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "tables_main.tex"
R = D["results"]


def esc(s):
    s = str(s)
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
                 ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"), (">=", r"$\geq$"), ("<=", r"$\leq$"), ("|", r"$|$")]:
        s = s.replace(a, b)
    return s.replace("$\\geq$", "$\\geq$")


def fmt(x, nd=2):
    if x is None:
        return "--"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int, float)):
        return f"{x:.{nd}f}" if abs(x) < 1000 else f"{x:.0f}"
    if isinstance(x, dict):
        return ", ".join(f"{k} {fmt(v, 1)}" for k, v in x.items())
    if isinstance(x, list):
        return "[" + ", ".join(fmt(v, nd) for v in x) + "]"
    if isinstance(x, str):
        # round long floats embedded in pre-formatted strings (e.g. "YES 2.8 [-0.2532661139875656, 5.891424008724423]")
        return re.sub(r"-?\d+\.\d{4,}", lambda m: f"{float(m.group(0)):.3f}", x)
    return str(x)


out = []
